// 设计目标（对应《决策辩论产品-埋点设计方案》）：
//
//  1. 绝不阻塞主流程。辩论是 60–120 秒的长任务，埋点故障不允许影响它。
//     因此 Emit 是非阻塞的：缓冲区满时直接丢弃并计数，而不是等待。
//  2. 区域隔离。event 带 zone 字段，decision（无菌区）与 execution（商业区）
//     的数据在采集层就分开，execution 的数据永不进入决策质量分析。
//  3. 每个事件都对应一个具体问题。回答不上来问题的事件不埋。
